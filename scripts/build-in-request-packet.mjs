import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const outPath = path.join(repoRoot, "data", "source-records-request-packets", "in-2024-precinct-results-request.md");

async function readJson(relativePath) {
  return JSON.parse((await readFile(path.join(repoRoot, relativePath), "utf8")).replace(/^\uFEFF/, ""));
}

function bulletList(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function findArtifact(inventory, id) {
  const artifact = inventory.loadedArtifacts.find((entry) => entry.id === id);
  if (!artifact) throw new Error(`Missing Indiana inventory artifact ${id}`);
  return artifact;
}

const inventory = await readJson("data/in-2024-data-coverage-inventory.json");
const enrInventory = await readJson("data/in-2024-official-enr-public-data-inventory.json");
const routing = await readJson("data/in-2024-county-request-routing-summary.json");

const president = findArtifact(inventory, "in-2024-official-enr-president");
const senate = findArtifact(inventory, "in-2024-official-enr-senate");
const jur = findArtifact(inventory, "in-2024-official-enr-jurisdiction-inventory");
const turnout = findArtifact(inventory, "in-2024-general-turnout");
const audit = findArtifact(inventory, "in-2024-vstop-general-audit-summary");
const publicInventory = findArtifact(inventory, "in-2024-official-enr-public-data-inventory");

const presidentRegions = enrInventory.retainedOfficeCategoryFiles.find((entry) => entry.officeCategoryId === "1019").regionCount;
const senateRegions = enrInventory.retainedOfficeCategoryFiles.find((entry) => entry.officeCategoryId === "1006").regionCount;

const md = `# Indiana 2024 Official Source Gap Request

Generated by \`scripts/build-in-request-packet.mjs\` from the Indiana coverage inventory, ENR public-data inventory, and county request-routing summary. This request seeks machine-readable official source records for the November 5, 2024 Indiana General Election. The public ENR county category JSON files currently available in this repository contain county totals, and the archived \`JurR_*_B.json\` county jurisdiction files contain office/contact and reporting-region/referendum structures, not candidate result rows.

## Evidence Already Checked

- ${president.sourceAuthority} President source: \`${president.localPath}\`, ${president.expectedCounts.rows} county rows, ${president.expectedCounts.stateTotal.toLocaleString("en-US")} votes. Caveat: ${president.caveats[0]}
- ${senate.sourceAuthority} U.S. Senate source: \`${senate.localPath}\`, ${senate.expectedCounts.rows} county rows. Caveat: ${senate.caveats[0]}
- ${jur.sourceAuthority} JurR inventory: \`${jur.localPath}\`, ${jur.expectedCounts.counties} county files. Caveat: ${jur.caveats[1]}
- Public ENR app scan: \`${publicInventory.localPath}\` reports ${presidentRegions} President county/locality regions, ${senateRegions} U.S. Senate county/locality regions, ${enrInventory.jurisdictionReportInventory.rescannedCandidateContainerCount} JurR candidate containers, and no public same-grain subcounty President/Senate candidate export.
- Live ENR public-path recheck (${enrInventory.livePublicPathRecheck.checkedAt}): ordinary public HTTPS GET requests returned HTTP 200 for ${enrInventory.livePublicPathRecheck.endpoints.length} documented archive endpoints, including settings, President, U.S. Senate, and statewide turnout JSON. Caveat: ${enrInventory.livePublicPathRecheck.conclusion}
- Indiana Election Division county turnout source: \`${turnout.localPath}\`, ${turnout.expectedCounts.rows} county rows, ${turnout.expectedCounts.ballotsCast.toLocaleString("en-US")} voters voting, and ${turnout.expectedCounts.registeredVoters.toLocaleString("en-US")} registered voters. Caveat: ${turnout.caveats[0]}
- VSTOP audit summary source: \`${audit.localPath}\`, ${audit.expectedCounts.rows} county audit-summary context rows. Caveat: ${audit.caveats[0]}
- The Indiana Election Division Election Administrator's Portal links a 2026 "Public Record Requests & Retentions" presentation, confirming records-request/retention guidance is part of the official administrator materials path.
- The Indiana Election Division Census Data, Statistics and Maps page links the statewide county precinct-count PDF. The routing summary generated from that PDF reports ${routing.totals.precincts.toLocaleString("en-US")} precincts, ${routing.totals.precinctSplits.toLocaleString("en-US")} precinct splits, and ${routing.totals.precinctsWithSplits.toLocaleString("en-US")} precincts with splits. Any result export should therefore identify whether rows are precincts, precinct splits, vote-center/reporting units, absentee/early/provisional units, or county summaries, and should include split identifiers where applicable.

Primary contact path currently listed by the Election Division: elections@iec.in.gov / 317-232-3939.

## Machine-Readable Routing Tracker

\`${routing.localArtifacts.routingCsv}\` and \`${routing.localArtifacts.routingSummary}\` are the operational follow-up tracker. The tracker pairs official ENR \`JurR_*_B.json\` county office/contact metadata with the official Indiana precinct/split-count PDF retained at \`${routing.localArtifacts.precinctCountPdf}\`. It covers ${routing.totals.counties} counties, ${routing.totals.precincts.toLocaleString("en-US")} precincts, ${routing.totals.precinctSplits.toLocaleString("en-US")} precinct splits, and ${routing.totals.precinctsWithSplits.toLocaleString("en-US")} precincts with splits. Use the statewide Election Division request first, then use county rows only if the state confirms no statewide same-grain export exists.

## Parser Requirements For Any Produced Export

${bulletList(routing.parserRequirements)}

## Records Request Text

Please provide, or identify the custodian for, the following machine-readable records for the November 5, 2024 Indiana General Election. We are seeking official source records suitable for public-interest source reconciliation. We are not asking for conclusions about misconduct.

Requested result records:
- President and Vice President result rows by precinct, township, ward, vote center/reporting unit, or the lowest county-subdivision level maintained by the office.
- U.S. Senator result rows at the same reporting-unit level and with the same local-unit identifiers.
- Field definitions or export layout documentation for county, FIPS/county code, local unit, precinct/reporting-unit code, precinct split code, candidate, party, vote total, contest name, office/contest ID, district ID where applicable, and ballot/reporting mode fields.
- A county-level file manifest that identifies whether each county reports consolidated vote-center totals, precinct totals, precinct-split totals, absentee/early/provisional rows, election-day rows, or other non-precinct reporting units.
- Certification/finality status and the county-level reconciliation method tying the local rows back to the official ENR county President and U.S. Senate totals.
- Any known caveats for duplicated precinct labels, renamed precincts, precinct splits, non-geographic rows, or report modes that should not be summed with standard precinct rows.

Requested turnout and registration records:
- State-native ballots-cast and registered-voter denominator rows by county or lower reporting unit.
- Denominator timing and definitions, including whether inactive voters, election-day registrations, provisional ballots, absentee ballots, overseas/federal-only ballots, and same-day changes are included.
- Expected statewide ballots-cast and registered-voter totals for reconciliation.

Requested geography and baseline records:
- Precinct, ward, township, vote-center/reporting-unit, or other local geometry/crosswalk files needed to join subcounty result rows.
- Historical county or subcounty presidential result baselines for 2020, 2016, and 2012, with source URLs, certification status, and parser notes.

Requested administration-context records:
- Post-election audit reports, audit unit lists, discrepancy summaries, and statewide audit findings.
- Recount records or confirmations of no applicable statewide recounts for President or U.S. Senate.
- Cast vote record availability documentation, export rules, public-records limitations, or county custodian routing guidance.
- Incident, correction, amended canvass, litigation, certification, and other post-election records that change or qualify published 2024 result data.

Preferred formats: original election-management-system export, CSV, XLSX, JSON, fixed-width text with layout, shapefile/GeoJSON/geodatabase for geometry, PDF reports with source tables, or database extract. Please preserve original filenames, timestamps, certification status, and export settings.

If the Indiana Election Division does not maintain any of these records statewide, please identify the county election offices or other custodians most likely to maintain them, and whether each county custodian should be asked for precinct, precinct-split, vote-center, or election-management-system export terminology.

## Local CivicResultMaps Artifacts To Cite In Follow-Up

- Request packet: \`data/source-records-request-packets/in-2024-precinct-results-request.md\`
- Request matrix: \`${inventory.requestMatrixArtifact}\`
- County routing CSV: \`${routing.localArtifacts.routingCsv}\`
- County routing summary: \`${routing.localArtifacts.routingSummary}\`
- Coverage inventory: \`data/in-2024-data-coverage-inventory.json\`
`;

await writeFile(outPath, md, "utf8");
console.log(`Wrote ${path.relative(repoRoot, outPath)}`);
